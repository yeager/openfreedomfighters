#!/usr/bin/env python3
"""Embed verified project-owned FSR 1 shader outputs in a C++ header."""

import argparse
import hashlib
import json
from pathlib import Path
import subprocess

PINNED_REVISION = "a21ffb8f6c13233ba336352bdff293894c706575"


def sha256(blob):
    return hashlib.sha256(blob).hexdigest()


def byte_array(name, blob):
    rows = [", ".join(f"0x{value:02x}" for value in blob[i:i + 16])
            for i in range(0, len(blob), 16)]
    return (f"alignas(4) inline constexpr unsigned char {name}[] = {{\n  "
            + ",\n  ".join(rows) + "\n};\n")


def validate_dxil_container(blob):
    if len(blob) < 32 or blob[:4] != b"DXBC":
        raise RuntimeError("DXC output is not a DXBC container")
    total_size = int.from_bytes(blob[24:28], "little")
    chunk_count = int.from_bytes(blob[28:32], "little")
    if total_size != len(blob) or chunk_count > (len(blob) - 32) // 4:
        raise RuntimeError("Invalid DXIL container bounds")
    for index in range(chunk_count):
        offset = int.from_bytes(blob[32 + index * 4:36 + index * 4], "little")
        if offset < 32 + chunk_count * 4 or offset > len(blob) - 8:
            raise RuntimeError("Invalid DXIL chunk offset")
        chunk_size = int.from_bytes(blob[offset + 4:offset + 8], "little")
        if chunk_size > len(blob) - offset - 8:
            raise RuntimeError("Invalid DXIL chunk size")
        if blob[offset:offset + 4] == b"DXIL":
            return
    raise RuntimeError("DXIL container has no DXIL program")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, required=True,
                        help="Pinned external GPUOpen FSR 1 checkout")
    parser.add_argument("--shader-output-dir", type=Path, required=True,
                        help="Directory generated by build_fsr1_shaders.py")
    parser.add_argument("--output", type=Path, required=True,
                        help="Generated header path")
    args = parser.parse_args()

    source_root = args.source_dir.resolve()
    output_root = args.shader_output_dir.resolve()
    output = args.output.resolve()
    if not source_root.is_dir() or not output_root.is_dir():
        parser.error("source and shader output directories must exist")
    if output_root == output or output_root in output.parents:
        parser.error("generated header cannot be written inside shader output directory")
    revision = subprocess.check_output(
        ["git", "-C", str(source_root), "rev-parse", "HEAD"], text=True).strip()
    if revision != PINNED_REVISION:
        parser.error(f"expected GPUOpen revision {PINNED_REVISION}, found {revision}")
    manifest = json.loads(
        (output_root / "fsr1_shader_manifest.json").read_text(encoding="utf-8"))
    if (manifest.get("revision") != PINNED_REVISION
            or not manifest.get("validation", {}).get("dxc")):
        parser.error("shader manifest is not pinned or lacks validated DXIL")
    for header_name, expected in manifest.get("upstream_header_sha256", {}).items():
        actual = sha256((source_root / "ffx-fsr" / header_name).read_bytes())
        if actual != expected:
            parser.error(f"pinned upstream header changed: {header_name}")

    pieces = [
        "// Generated by tools/embed_fsr1_shaders.py; do not edit.\n",
        f"// GPUOpen FidelityFX-FSR revision: {PINNED_REVISION}\n",
        "// Generated from project wrappers and pinned public upstream headers.\n",
        "// AMD and Michal Drobot notices: assets/shaders/FSR1_UPSTREAM_NOTICE.txt\n",
        "#pragma once\n\nnamespace off::platform::generated {\n",
    ]
    shader_names = ("fullscreen_vert", "easu", "rcas")
    for name in shader_names:
        spec = manifest.get("passes", {}).get(name)
        if not spec:
            parser.error(f"manifest is missing {name} shader pass")
        pieces.append(
            f"// {name.upper()} wrapper SHA256: {spec['wrapper_sha256']}\n")
        for suffix in ("spv", "msl", "dxil"):
            filename = f"fsr1_{name}.{suffix}"
            digest = spec.get("outputs_sha256", {}).get(filename)
            if not digest:
                parser.error(f"manifest is missing generated digest: {filename}")
            pieces.append(f"// {name.upper()} {suffix.upper()} SHA256: {digest}\n")
    for name in shader_names:
        spec = manifest.get("passes", {}).get(name)
        if not spec:
            parser.error(f"manifest is missing {name} shader pass")
        wrapper = (Path(__file__).resolve().parents[1] / "assets" / "shaders"
                   / spec["wrapper"])
        if sha256(wrapper.read_bytes()) != spec.get("wrapper_sha256"):
            parser.error(f"project FSR 1 wrapper changed: {wrapper.name}")
        for suffix in ("spv", "msl", "dxil"):
            filename = f"fsr1_{name}.{suffix}"
            blob = (output_root / filename).read_bytes()
            expected = spec.get("outputs_sha256", {}).get(filename)
            if not expected or sha256(blob) != expected:
                parser.error(f"generated FSR 1 artifact changed: {filename}")
            if suffix == "spv" and not blob.startswith(b"\x03\x02\x23\x07"):
                parser.error(f"invalid SPIR-V magic: {filename}")
            if suffix == "dxil":
                validate_dxil_container(blob)
            if suffix == "msl":
                metal = blob.decode("utf-8")
                if ")OFF_FSR1_MSL\"" in metal:
                    parser.error("generated MSL collides with C++ literal delimiter")
                pieces.append(
                    f'inline constexpr char fsr1_{name}_msl[] = '
                    f'R"OFF_FSR1_MSL({metal})OFF_FSR1_MSL";\n')
            else:
                pieces.append(byte_array(f"fsr1_{name}_{suffix}", blob))
    pieces.append("} // namespace off::platform::generated\n")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(pieces), encoding="utf-8")
    print(f"Embedded pinned FSR 1 shader outputs in {output}")


if __name__ == "__main__":
    main()
